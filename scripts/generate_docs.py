"""Regenerate the configuration-derived parts of the documentation.

Writes docs/VARIABLE_DICTIONARY.md and docs/PARAMETER_REGISTRY.md in full, and replaces
the blocks between `<!-- BEGIN GENERATED -->` and `<!-- END GENERATED -->` in
docs/CAUSAL_ASSUMPTIONS.md and docs/MATHEMATICAL_EQUATIONS.md.

Run after any change to config/model_config.json:
    backend/.venv/bin/python scripts/generate_docs.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from twin_engine import config_hash, default_config  # noqa: E402
from twin_engine.config import references  # noqa: E402
from twin_engine.equations import all_equations  # noqa: E402
from twin_engine.graph import declared_loops, detect_loops  # noqa: E402
from twin_engine.params import list_parameters  # noqa: E402

DOCS = ROOT / "docs"
REF_IDS = {r["id"]: r for r in references()}


def esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def header(title: str, cfg: dict) -> str:
    return (f"# {title}\n\n"
            f"> Generated by `scripts/generate_docs.py` from `config/model_config.json` "
            f"(configuration hash `{config_hash(cfg)}`). Do not edit by hand.\n\n"
            f"> **Parameter status: {cfg['parameter_set']['status']}.** {cfg['parameter_set']['statement']['en']}\n\n")


def variable_dictionary(cfg: dict) -> str:
    out = [header("Variable Dictionary", cfg)]
    out.append("All variables are stored internally on a common 0–1 scale. Raw measurements are converted with the "
               "normalisation engine using the reference bounds below (positive: z = (x − L)/(U − L); negative: "
               "z = (U − x)/(U − L); clipped to [0, 1]; missing values stay missing).\n\n")
    out.append("Roles: **state** = dynamic state X(t); **context** = observed context indicator Z(t); "
               "**derived** = derived operational indicator (R, L).\n\n")
    out.append("| ID | Symbol | Variable (EN / TR) | Domain | Role | Unit | L | U | Direction | Demo initial | Measurement evidence |\n"
               "|---|---|---|---|---|---|---|---|---|---|---|\n")
    for v in cfg["variables"]:
        m = v["measurement"]
        out.append(f"| {v['id']} | `{v['symbol']}` | {esc(v['labels']['en'])} / {esc(v['labels']['tr'])} | {v['domain']} | {v['role']} | "
                   f"{esc(m['unit'])} | {m['lower']} | {m['upper']} | {m['direction']} | {v['initial']:.2f} | {v['measurement_evidence']} |\n")
    out.append("\n## Definitions, measurement sources and notes\n\n")
    for v in cfg["variables"]:
        m = v["measurement"]
        out.append(f"### {v['id']} · `{v['symbol']}` · {v['labels']['en']} ({v['labels']['tr']})\n\n")
        out.append(f"- **Definition (EN):** {v['definition']['en']}\n- **Tanım (TR):** {v['definition']['tr']}\n")
        out.append(f"- **Key in code:** `{v['key']}`\n- **Measurement:** {m['unit']}, reference bounds [{m['lower']}, {m['upper']}], {m['direction']} direction\n")
        out.append(f"- **Example aggregate sources:** {'; '.join(m['sources'])}\n")
        for c in m.get("components", []):
            out.append(f"  - component: {c['name']} ({c['unit']}, [{c['lower']}, {c['upper']}], {c['direction']})\n")
        if v["references"]:
            out.append(f"- **References:** {', '.join(v['references'])}\n")
        if v.get("notes"):
            out.append(f"- **Notes:** {v['notes']}\n")
        out.append("\n")
    out.append("## Stock-flow quantities\n\n| Key | Name | Unit | Kind |\n|---|---|---|---|\n")
    for f in cfg["flow_nodes"]:
        out.append(f"| `{f['key']}` | {f['labels']['en']} / {f['labels']['tr']} | {f['unit']} | {f['kind']} |\n")
    out.append("\n> Terminology: `C` (`school_belonging`) is school belonging; `C_flow` (`completed_process_flow`) is the "
               "completed support-process flow. They are never interchangeable.\n\n")
    out.append("## Interventions U(t) and external conditions D(t)\n\n| Key | Name | Notes |\n|---|---|---|\n")
    for i in cfg["interventions"]:
        out.append(f"| `{i['key']}` | {i['labels']['en']} / {i['labels']['tr']} | intensity 0–1; cost parameter `{i['cost_param']}` |\n")
    for e in cfg["external_conditions"]:
        out.append(f"| `{e['key']}` | {e['labels']['en']} / {e['labels']['tr']} | default {e['default']}; {e['description']['en']} |\n")
    return "".join(out)


def parameter_registry(cfg: dict) -> str:
    out = [header("Parameter Registry", cfg)]
    out.append("Every numeric parameter of the model. Edge coefficients are addressed as `edge.<id>` and stored on the "
               "relationship itself; the sign is stored separately (coefficients are magnitudes). `range` is the "
               "plausible interval used by uncertainty and sensitivity analysis; `min`/`max` are hard validation bounds.\n\n"
               "Provenance classes: **illustrative** (demonstration value), **hypothesized** (coefficient of a research "
               "hypothesis, H), **expert** (elicited), **literature** (from recorded literature ranges), **calibrated** "
               "(estimated from aggregate data), **structural** (accounting identity).\n\n")
    out.append("The baseline intercepts `b.*`, `b.L`, `flow.I_base` and the initial backlog `Q(0)` are *derived* by "
               "`scripts/anchor_demo_baseline.py` so that the synthetic demonstration baseline is an equilibrium; they "
               "inherit the illustrative status of the coefficients they are computed from.\n\n")
    groups: dict[str, list] = {}
    for p in list_parameters(cfg, include_disabled=True):
        groups.setdefault(p["group"], []).append(p)
    for g in ("edge", "baseline", "transition", "flow", "weights", "cost"):
        rows = groups.get(g, [])
        if not rows:
            continue
        out.append(f"## {g}\n\n| ID | Symbol | Value | Range | Bounds | Unit | Provenance | Description |\n|---|---|---|---|---|---|---|---|\n")
        for p in rows:
            rng = f"[{p['range'][0]:.3g}, {p['range'][1]:.3g}]" if p.get("range") else "—"
            desc = p.get("description", {}).get("en", "") if isinstance(p.get("description"), dict) else ""
            if g == "edge":
                desc = f"{'+' if p['sign'] > 0 else '−'} {p['source']} → {p['target']} ({p['kind']}, evidence {p['evidence']}{'' if p['enabled'] else ', disabled'}). {desc}"
            out.append(f"| `{p['id']}` | {esc(p['symbol'])} | {p['value']:.6g} | {rng} | [{p['min']}, {p['max']}] | {esc(p['unit'])} | {p['provenance']} | {esc(desc)} |\n")
        out.append("\n")
    return "".join(out)


def causal_block(cfg: dict) -> str:
    out = ["### Relationship table\n\n| ID | Hyp. | Source → Target | Kind | Sign | Coef. | Range | Evidence | Confidence | References |\n"
           "|---|---|---|---|---|---|---|---|---|---|\n"]
    for e in cfg["edges"]:
        rng = f"[{e['range'][0]}, {e['range'][1]}]" if e.get("range") else "—"
        refs = ", ".join(e["references"]) or "—"
        out.append(f"| `{e['id']}` | {e.get('hypothesis') or ''} | `{e['source']}` → `{e['target']}` | {e['kind']} | {'+' if e['sign'] > 0 else '−'} | "
                   f"{e['coefficient']:.3f} | {rng} | {e['evidence']} | {e['confidence']} | {refs} |\n")
    out.append("\n### Declared feedback loops\n\n")
    for l in declared_loops(cfg):
        out.append(f"- **{l['id']} — {l['labels']['en']}** (declared {l['polarity']}, computed {l['computed_polarity']}, "
                   f"closed: {l['closed']}): {' → '.join(l['nodes'])} → {l['nodes'][0]}. {l['description']['en']}\n")
    det = detect_loops(cfg)
    out.append(f"\nAutomatic cycle enumeration finds **{len(det)}** simple feedback cycles among enabled relationships "
               f"({sum(d['polarity'] == 'reinforcing' for d in det)} reinforcing, {sum(d['polarity'] == 'balancing' for d in det)} balancing). "
               "The ten shortest:\n\n")
    for d in det[:10]:
        out.append(f"- {d['polarity']}: {' → '.join(d['nodes'])} → {d['nodes'][0]}{' (= ' + d['declared_as'] + ')' if d['declared_as'] else ''}\n")
    return "".join(out)


def equations_block(cfg: dict) -> str:
    eq = all_equations(cfg)
    out = ["### State target equations (current coefficients)\n\n"]
    for e in eq["state"]:
        out.append(f"```text\n{e['symbolic']}\n{e['numeric']}\n{e['transition']}\n```\n\n")
    out.append("### Observed context indicators with responsive deviations\n\n")
    for e in eq["context"]:
        out.append(f"```text\n{e['symbolic']}\n{e['numeric']}\n```\n\n")
    out.append("### Stock-flow block\n\n")
    for e in eq["flows"]:
        out.append(f"**{e['name']}**\n\n```text\n{e['symbolic']}\n{e['numeric']}\n```\n\n")
    out.append("### Readiness indices\n\n")
    for e in eq["indices"]:
        out.append(f"```text\n{e['symbolic']}   {e['numeric']}\n```\n\n")
    return "".join(out)


def replace_block(path: Path, content: str) -> None:
    text = path.read_text(encoding="utf-8")
    new, n = re.subn(r"<!-- BEGIN GENERATED -->.*?<!-- END GENERATED -->",
                     "<!-- BEGIN GENERATED -->\n" + content + "\n<!-- END GENERATED -->", text, flags=re.S)
    if n != 1:
        raise RuntimeError(f"{path} must contain exactly one generated block")
    path.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    cfg = default_config()
    (DOCS / "VARIABLE_DICTIONARY.md").write_text(variable_dictionary(cfg), encoding="utf-8")
    (DOCS / "PARAMETER_REGISTRY.md").write_text(parameter_registry(cfg), encoding="utf-8")
    replace_block(DOCS / "CAUSAL_ASSUMPTIONS.md", causal_block(cfg))
    replace_block(DOCS / "MATHEMATICAL_EQUATIONS.md", equations_block(cfg))
    print("documentation regenerated, config hash", config_hash(cfg))
