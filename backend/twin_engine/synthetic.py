"""Deterministic synthetic dataset generator (Section 18).

Produces monthly AGGREGATE institutional observations generated by the model itself
under perturbed "true" parameters, plus temporally smoothed observation noise and
configurable missingness. Every record is labelled SYNTHETIC. No person-level data,
identifiers or demographic attributes are generated.

Because the generating parameters are stored with the dataset, synthetic data supports
parameter-recovery checks of the calibration module.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

import numpy as np

from .model import compile_model
from .params import get_bounds, get_value
from .scenarios import ResolvedScenario, baseline_from_config, resolve
from .schemas import ALL_VARS, CONTEXT_VARS
from .simulator import run

# Illustrative seasonal academic-load profile by calendar month (1..12). SYNTHETIC.
SEASONAL_LOAD = {9: 0.45, 10: 0.50, 11: 0.60, 12: 0.55, 1: 0.65, 2: 0.40, 3: 0.50, 4: 0.55, 5: 0.60, 6: 0.65, 7: 0.30, 8: 0.30}

DEFAULT_TRUTH_PARAMS = ["lambda.T", "lambda.C", "lambda.K", "edge.H1", "edge.H2", "edge.H4", "edge.H7", "edge.H9", "edge.SOC-T-C"]


def _periods(start: str, n: int) -> list[str]:
    y, mo = (int(x) for x in start.split("-"))
    out = []
    for _ in range(n):
        out.append(f"{y:04d}-{mo:02d}")
        mo += 1
        if mo > 12:
            mo, y = 1, y + 1
    return out


def generate(
    cfg: dict[str, Any],
    months: int = 36,
    seed: int = 42,
    missing_rate: float = 0.05,
    noise_sd: float = 0.02,
    smoothing: float = 0.6,
    start_period: str = "2023-09",
    truth_perturbation: float = 0.15,
    truth_params: Optional[list[str]] = None,
    seasonal: bool = True,
    intervention: Optional[dict[str, Any]] = None,
    include_intervention: bool = True,
    name: Optional[str] = None,
) -> dict[str, Any]:
    if not (6 <= months <= 120):
        raise ValueError("months must be between 6 and 120")
    if not (0 <= missing_rate <= 0.5):
        raise ValueError("missing_rate must lie in [0, 0.5]")
    if not (0 <= noise_sd <= 0.2):
        raise ValueError("noise_sd must lie in [0, 0.2]")
    if not (0 <= smoothing < 1):
        raise ValueError("smoothing (AR(1) coefficient) must lie in [0, 1)")
    rng = np.random.default_rng(seed)
    N = months - 1
    periods = _periods(start_period, months)

    # 1. "True" generating parameters (perturbed illustrative values)
    truth: dict[str, float] = {}
    for pid in truth_params or DEFAULT_TRUTH_PARAMS:
        v0 = get_value(cfg, pid)
        lo, hi = get_bounds(cfg, pid)
        truth[pid] = float(np.clip(v0 * (1 + rng.uniform(-truth_perturbation, truth_perturbation)), lo, hi))

    # 2. Smooth exogenous context paths and seasonal academic load
    sc = baseline_from_config(cfg)
    sc["horizon_months"] = N
    init = sc["initial_state"]
    ctx_sched = {}
    for sym in CONTEXT_VARS:
        dev, path = 0.0, []
        for _ in range(N + 1):
            dev = 0.8 * dev + rng.normal(0, 0.012)
            path.append(float(np.clip(init[sym] + dev, 0, 1)))
        ctx_sched[sym] = {"values": path}
    sc["context_schedule"] = ctx_sched
    start_month = int(periods[0].split("-")[1])
    if seasonal:
        load = [SEASONAL_LOAD[((start_month - 1 + t) % 12) + 1] for t in range(N + 1)]
        sc["external"]["academic_load"] = {"values": load}
    iv_meta = None
    if include_intervention:
        iv = intervention or {"key": "U_access", "intensity": 0.5, "start_month": max(2, (2 * months) // 3), "ramp_months": 3}
        sc["interventions"] = [iv]
        iv_meta = {**iv, "start_period": periods[min(iv["start_month"], N)]}

    rs, eff_cfg = resolve(cfg, sc)
    m = compile_model(eff_cfg).with_params(truth)
    raw = run(m, rs)
    V = raw["V"]

    # 3. Observation model: AR(1)-smoothed noise, clipping, MCAR missingness
    obs: dict[str, list[Optional[float]]] = {}
    for k, sym in enumerate(ALL_VARS):
        e, series = 0.0, []
        for t in range(N + 1):
            e = smoothing * e + np.sqrt(1 - smoothing ** 2) * rng.normal(0, noise_sd)
            val = float(np.clip(V[t, k] + e, 0, 1))
            series.append(None if (t > 0 and rng.random() < missing_rate) else round(val, 5))
        obs[sym] = series

    # 4. Aggregate workload counts with exact observed mass balance. Demand is Poisson around
    #    the model's expected inflow; completions follow simulated capacity plus a mean-reverting
    #    correction (κ = 0.5) toward the simulated backlog, so counts stay consistent with the
    #    generating model instead of drifting as an unbounded random walk.
    kappa = 0.5
    Q_obs: list[Optional[float]] = [float(round(raw["Q"][0]))]
    I_obs: list[Optional[float]] = [None]
    C_obs: list[Optional[float]] = [None]
    for t in range(1, N + 1):
        inc = float(rng.poisson(max(raw["I"][t], 0)))
        target = raw["C_flow"][t] + kappa * (Q_obs[-1] - raw["Q"][t - 1]) + (inc - raw["I"][t])
        comp = float(min(Q_obs[-1] + inc, max(0.0, round(target))))
        I_obs.append(inc); C_obs.append(comp); Q_obs.append(Q_obs[-1] + inc - comp)
    n_resp = [int(rng.integers(160, 280)) for _ in range(N + 1)]

    U_series = {k: [float(x) for x in raw["U"][:, i]] for i, k in enumerate(m.interventions) if np.any(raw["U"][:, i] > 0)}
    return {
        "name": name or f"Synthetic monthly series (seed {seed})",
        "data_class": "SYNTHETIC",
        "frequency": "monthly",
        "periods": periods,
        "record_labels": ["SYNTHETIC"] * len(periods),
        "variables": obs,
        "flows": {"I": I_obs, "C_flow": C_obs, "Q": Q_obs},
        "counts": {"n_respondents": n_resp},
        "interventions": U_series,
        "external": {"academic_load": [float(x) for x in raw["D"][:, m.externals.index("academic_load")]]},
        "value_scale": "normalized",
        "provenance": {
            "source": "twin_engine.synthetic.generate",
            "generator": {"seed": seed, "months": months, "missing_rate": missing_rate, "noise_sd": noise_sd,
                          "smoothing": smoothing, "truth_perturbation": truth_perturbation, "seasonal": seasonal,
                          "intervention": iv_meta},
            "statement": "SYNTHETIC DEMONSTRATION DATA — NOT REAL SCHOOL MEASUREMENTS.",
            "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        },
        "truth": truth,
    }
